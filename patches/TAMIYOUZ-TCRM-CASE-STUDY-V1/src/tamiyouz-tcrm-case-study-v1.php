add_action('init', function () {
    if (!post_type_exists('tyz_case_study')) return;

    $version = '1.0.0';
    if (get_option('tamiyouz_tcrm_case_study_v1') === $version) return;

    $slug = 'tcrm';
    $existing = get_page_by_path($slug, OBJECT, 'tyz_case_study');
    $data = array(
        'post_type' => 'tyz_case_study',
        'post_name' => $slug,
        'post_title' => 'TCRM — منظومة CRM وتشغيل مخصصة',
        'post_excerpt' => 'دراسة حالة لمنظومة CRM مخصصة تجمع قمع المبيعات وSLA والتقويم وملف العميل والاجتماعات والتكاملات في تجربة تشغيل واحدة.',
        'post_content' => tyz_tcrm_case_study_v1_content(),
        'post_status' => 'publish',
        'comment_status' => 'closed',
        'menu_order' => 10,
    );

    if ($existing) {
        if (!get_post_meta($existing->ID, '_tyz_seeded_tcrm_case_v1', true)) {
            update_option('tamiyouz_tcrm_case_study_v1', $version, false);
            return;
        }
        $data['ID'] = $existing->ID;
        $post_id = wp_update_post(wp_slash($data), true);
    } else {
        $post_id = wp_insert_post(wp_slash($data), true);
    }

    if (!is_wp_error($post_id) && $post_id) {
        update_post_meta($post_id, '_tyz_seeded_tcrm_case_v1', '1');
        update_option('tamiyouz_tcrm_case_study_v1', $version, false);
    }
}, 35);

add_action('wp_head', function () {
    if (!is_singular('tyz_case_study')) return;
    $post = get_queried_object();
    if (!$post || $post->post_name !== 'tcrm') return;

    $schema = array(
        '@context' => 'https://schema.org',
        '@graph' => array(
            array(
                '@type' => 'Article',
                '@id' => get_permalink($post) . '#case-study',
                'headline' => get_the_title($post),
                'description' => get_the_excerpt($post),
                'mainEntityOfPage' => get_permalink($post),
                'author' => array('@type'=>'Organization','name'=>'Tamiyouz','url'=>home_url('/')),
                'publisher' => array('@type'=>'Organization','name'=>'Tamiyouz','url'=>home_url('/')),
            ),
            array(
                '@type' => 'BreadcrumbList',
                'itemListElement' => array(
                    array('@type'=>'ListItem','position'=>1,'name'=>'تميز','item'=>home_url('/')),
                    array('@type'=>'ListItem','position'=>2,'name'=>'أعمالنا','item'=>home_url('/work/')),
                    array('@type'=>'ListItem','position'=>3,'name'=>'TCRM','item'=>get_permalink($post)),
                ),
            ),
        ),
    );

    echo '<script type="application/ld+json">' . wp_json_encode($schema, JSON_UNESCAPED_UNICODE|JSON_UNESCAPED_SLASHES) . '</script>' . "\n";
}, 25);
